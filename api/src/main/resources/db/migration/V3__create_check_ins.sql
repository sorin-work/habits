CREATE TABLE check_ins (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    habit_id   BIGINT       NOT NULL REFERENCES habits (id) ON DELETE CASCADE,
    day        DATE         NOT NULL,
    value      INT          NOT NULL,
    note       VARCHAR(500),
    created_at TIMESTAMP    NOT NULL,
    updated_at TIMESTAMP    NOT NULL,
    CONSTRAINT check_ins_value_check CHECK (value > 0)
);

-- One check-in per habit and day; also serves range lookups by habit.
CREATE UNIQUE INDEX check_ins_habit_day_key ON check_ins (habit_id, day);
