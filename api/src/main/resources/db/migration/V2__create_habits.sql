CREATE TABLE habits (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name           VARCHAR(80)  NOT NULL,
    description    VARCHAR(500),
    color          VARCHAR(7)   NOT NULL,
    schedule_type  VARCHAR(16)  NOT NULL,
    schedule_days  VARCHAR(20),
    times_per_week INT,
    target         INT,
    unit           VARCHAR(20),
    start_date     DATE         NOT NULL,
    created_at     TIMESTAMP    NOT NULL,
    updated_at     TIMESTAMP    NOT NULL,
    CONSTRAINT habits_schedule_type_check CHECK (schedule_type IN ('DAILY', 'WEEKDAYS', 'WEEKLY')),
    CONSTRAINT habits_times_per_week_check CHECK (times_per_week IS NULL OR times_per_week BETWEEN 1 AND 7),
    CONSTRAINT habits_target_check CHECK (target IS NULL OR target > 0)
);

CREATE INDEX habits_user_id_idx ON habits (user_id);
